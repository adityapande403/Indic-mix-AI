"""Enterprise LLM Privacy Proxy & Session Re-hydration Engine.

Provides bidirectional sanitization and de-anonymization for LLM and enterprise workflows:
1. Replaces sensitive customer PII with numbered, context-preserving placeholders ([NAME_1], [PHONE_1], [UPI_1]).
2. Preserves critical transaction amounts (₹1500, Rs 500), dates, and safe business terms.
3. Automatically re-hydrates LLM responses with original sensitive entities upon authorization.
"""

from __future__ import annotations

import re
import uuid
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Tuple

from .pii_detection import EntitySpan, HybridPIIDetector, merge_and_deduplicate_spans


@dataclass
class AnonymizationSession:
    """Stateful privacy session enabling bidirectional token re-hydration."""
    session_id: str
    original_text: str
    sanitized_text: str
    token_to_entity: Dict[str, str] = field(default_factory=dict)
    entity_to_token: Dict[str, str] = field(default_factory=dict)
    detected_spans: List[EntitySpan] = field(default_factory=list)

    def deanonymize(self, text_from_llm: str) -> str:
        """Re-hydrate text generated by downstream LLM back into authorized customer values."""
        if not text_from_llm or not self.token_to_entity:
            return text_from_llm

        rehydrated = text_from_llm
        for token, original_val in self.token_to_entity.items():
            rehydrated = rehydrated.replace(token, original_val)
        return rehydrated

    def to_dict(self) -> Dict[str, Any]:
        return {
            "session_id": self.session_id,
            "original_text": self.original_text,
            "sanitized_text": self.sanitized_text,
            "token_mapping": self.token_to_entity,
            "entities": [s.to_dict() for s in self.detected_spans]
        }


class EnterprisePrivacyProxy:
    """Production LLM Middleware Gateway for Code-Mixed Indic Text."""

    def __init__(self, pii_detector: Optional[HybridPIIDetector] = None):
        self.detector = pii_detector or HybridPIIDetector(enable_model=True)
        self.sessions: Dict[str, AnonymizationSession] = {}

    def get_session(self, session_id: str) -> Optional[AnonymizationSession]:
        """Retrieve existing session by ID."""
        return self.sessions.get(session_id)

    def anonymize(
        self,
        text: str,
        redact_names: bool = True,
        session_id: Optional[str] = None
    ) -> AnonymizationSession:
        """Sanitize customer text for LLM consumption using numbered entity placeholders."""
        sid = session_id or f"sess_{uuid.uuid4().hex[:10]}"
        if not text:
            return AnonymizationSession(
                session_id=sid,
                original_text="",
                sanitized_text="",
                token_to_entity={},
                entity_to_token={},
                detected_spans=[]
            )

        # 1. Detect PII spans
        raw_spans = self.detector.detect(text)
        
        # Filter spans if name redaction is disabled
        filtered_spans = [
            s for s in raw_spans
            if s.entity_type != "NAME" or redact_names
        ]
        spans = merge_and_deduplicate_spans(filtered_spans)

        # 2. Build indexed placeholders e.g. [NAME_1], [PHONE_1]
        counts: Dict[str, int] = {}
        token_to_entity: Dict[str, str] = {}
        entity_to_token: Dict[str, str] = {}
        span_tokens: List[Tuple[EntitySpan, str]] = []

        for s in spans:
            # Check if this exact entity text was already encountered in this session
            key = (s.entity_type, s.text)
            if s.text in entity_to_token:
                placeholder = entity_to_token[s.text]
            else:
                counts[s.entity_type] = counts.get(s.entity_type, 0) + 1
                placeholder = f"[{s.entity_type}_{counts[s.entity_type]}]"
                token_to_entity[placeholder] = s.text
                entity_to_token[s.text] = placeholder

            span_tokens.append((s, placeholder))

        # 3. Replace spans in reverse offset order to maintain slicing accuracy
        sorted_spans = sorted(span_tokens, key=lambda pair: pair[0].start, reverse=True)
        chars = list(text)

        for s, token in sorted_spans:
            chars[s.start:s.end] = list(token)

        sanitized = "".join(chars)

        session = AnonymizationSession(
            session_id=sid,
            original_text=text,
            sanitized_text=sanitized,
            token_to_entity=token_to_entity,
            entity_to_token=entity_to_token,
            detected_spans=spans
        )
        self.sessions[sid] = session
        return session

    def deanonymize(self, text_from_llm: str, token_mapping: Dict[str, str]) -> str:
        """Standalone de-anonymization using a provided token mapping."""
        if not text_from_llm or not token_mapping:
            return text_from_llm

        result = text_from_llm
        for token, original_val in token_mapping.items():
            result = result.replace(token, original_val)
        return result

    def deanonymize_session(self, session_id: str, text_from_llm: str) -> str:
        """De-anonymize LLM text using an active session."""
        session = self.get_session(session_id)
        if not session:
            raise KeyError(f"Session '{session_id}' not found.")
        return session.deanonymize(text_from_llm)
